const questions = [];
const blocks = rawText.split(/(?=\d{2}\.\s+প্রশ্ন:)/);

for (const block of blocks) {
    if (!block.trim()) continue;
    
    // Normalise whitespace
    let text = block.replace(/\r?\n/g, ' ').replace(/\s+/g, ' ').trim();
    
    const numMatch = text.match(/^(\d{2})\.\s+প্রশ্ন:\s+(.*?)\s+\(a\)/);
    if (!numMatch) continue;
    
    const id = parseInt(numMatch[1], 10);
    const questionText = numMatch[2].trim();
    
    // Extract options
    let remain = text.substring(numMatch[0].length - 3); // keep '(a)'
    
    const optMatch = remain.match(/\(a\)\s*(.*?)\s+\(b\)\s*(.*?)\s+\(c\)\s*(.*?)\s+\(d\)\s*(.*?)\s+সঠিক উত্তর:/);
    
    let options = [];
    if (optMatch) {
        options = [optMatch[1].trim(), optMatch[2].trim(), optMatch[3].trim(), optMatch[4].trim()];
    }
    
    const ansMatch = text.match(/সঠিক উত্তর:\s*(?:\(a\)|\(b\)|\(c\)|\(d\))\s*(?:ব্যাখ্যা:\s*(.*))?$/);
    
    let correctAnswerStr = text.match(/সঠিক উত্তর:\s*\(((?:a|b|c|d))\)/);
    let correctAnswerIndex = -1;
    if (correctAnswerStr) {
        const val = correctAnswerStr[1];
        if (val === 'a') correctAnswerIndex = 0;
        else if (val === 'b') correctAnswerIndex = 1;
        else if (val === 'c') correctAnswerIndex = 2;
        else if (val === 'd') correctAnswerIndex = 3;
    }
    
    let correctAnswer = options[correctAnswerIndex] || '';
    if (!correctAnswer) {
      correctAnswer = "সঠিক উত্তর নেই";
    }

    let explanation = '';
    if (ansMatch && ansMatch[1]) {
        explanation = ansMatch[1].trim();
    }
    
    questions.push({
        id,
        question_text: questionText,
        options,
        correct_answer: correctAnswer,
        explanation,
        time_limit: 52
    });
}

